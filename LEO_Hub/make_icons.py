"""Draw the LEO house icon as PNG (192 + 512, full-bleed so it also works as a maskable icon) and emit C arrays."""
import io, sys, pathlib
from PIL import Image, ImageDraw
out_h = pathlib.Path(sys.argv[1])
def icon(size):
    s = size / 96.0
    img = Image.new("RGB", (size, size), (12, 15, 18))           # full-bleed background (maskable-safe)
    d = ImageDraw.Draw(img)
    w = max(2, round(6 * s)); teal = (52, 211, 176)
    # same path as icon.svg, scaled into the centre safe zone (80 %)
    k = 0.8; off = size * (1 - k) / 2
    P = lambda x, y: (off + x * s * k, off + y * s * k)
    d.line([P(22, 46), P(48, 24), P(74, 46)], fill=teal, width=w, joint="curve")
    d.line([P(28, 42), P(28, 72), P(68, 72), P(68, 42)], fill=teal, width=w, joint="curve")
    d.line([P(42, 72), P(42, 56), P(54, 56), P(54, 72)], fill=teal, width=w, joint="curve")
    for pt in [P(22, 46), P(74, 46), P(48, 24)]:
        r = w / 2; d.ellipse([pt[0] - r, pt[1] - r, pt[0] + r, pt[1] + r], fill=teal)
    b = io.BytesIO(); img.save(b, "PNG", optimize=True); return b.getvalue()
lines = ["// PNG app icons for installing the web app (generated by make_icons.py)"]
for size in (192, 512):
    data = icon(size)
    lines.append("static const uint8_t ICON_%d_PNG[] PROGMEM = {" % size)
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join("0x%02x" % c for c in data[i:i + 24]) + ",")
    lines.append("};")
    print(size, len(data), "bytes")
out_h.write_text("\n".join(lines) + "\n", encoding="utf-8")
